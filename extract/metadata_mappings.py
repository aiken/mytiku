# ----------------------------------------------------------------------
# 标准化函数
# ----------------------------------------------------------------------
def standardize_school(school_name: str) -> str:
    """标准化学校名称"""
    if not school_name or school_name == "未知":
        return "未知"
    
    # 直接匹配
    if school_name in SCHOOL_ALIASES:
        return SCHOOL_ALIASES[school_name]
    
    # 关键词匹配
    for keyword, standard in SCHOOL_KEYWORDS.items():
        if keyword in school_name:
            return standard
    
    return school_name


def standardize_district(district_name: str) -> str:
    """标准化区名"""
    if not district_name or district_name == "未知":
        return "未知"
    
    # 直接匹配
    if district_name in DISTRICT_STANDARDIZATION:
        return DISTRICT_STANDARDIZATION[district_name]
    
    # 尝试去掉"区"后缀匹配
    name_without_suffix = district_name.replace("区", "")
    if name_without_suffix in DISTRICT_STANDARDIZATION:
        return DISTRICT_STANDARDIZATION[name_without_suffix]
    
    return district_name


def standardize_exam_type(exam_type: str) -> str:
    """标准化考试类型"""
    if not exam_type or exam_type == "未知":
        return "未知"
    
    # 直接匹配
    if exam_type in EXAM_TYPE_STANDARDIZATION:
        return EXAM_TYPE_STANDARDIZATION[exam_type]
    
    # 关键词匹配
    for keyword, standard in EXAM_TYPE_STANDARDIZATION.items():
        if keyword in exam_type:
            return standard
    
    return exam_type


def standardize_metadata(district: str, school: str, exam_type: str) -> tuple:
    """标准化所有元数据，返回 (district, school, exam_type)"""
    return (
        standardize_district(district),
        standardize_school(school),
        standardize_exam_type(exam_type),
    )
